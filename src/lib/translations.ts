export function translate(text: string, locale: Locale): string {
  if (locale === "en") return text;
  const key = text.trim().replace(/\s+/g, " ");
  const pair = translations[key];
  if (!pair) return text;
  return text.replace(text.trim(), pair[locale === "fr" ? 0 : 1]);
}
